#!/usr/bin/env python3
"""Generate the Darwin-ABI adapters for Wine syscalls that take more than 8 arguments.

Why: the Windows ARM64 ABI (used by the PE side that calls the syscall dispatcher) gives every stack-passed
argument an 8-byte slot. Apple's ARM64 ABI (darwinpcs) packs small stack arguments at their natural size, so
NtMapViewOfSection(..., ULONG alloc_type, ULONG protect) reads 'protect' at [sp+4] instead of [sp+8] and the
Unix function (compiled for darwinpcs) sees garbage. Each syscall with more than 8 arguments gets a thunk whose
parameters are all 64-bit integers (8-byte slots, exactly what the dispatcher copies from the PE stack) and
which calls the real function with the proper types, so the compiler repacks the arguments the Darwin way.

Usage: gen-apple-stack-thunks.py <wine-src>      (rewrites the generated headers in place)
"""
import re, sys, os

src = sys.argv[1]
mods = {
    'ntdll': dict(spec='dlls/ntdll/ntdll.spec', headers=['include/winternl.h'], out='dlls/ntdll/unix'),
    'win32u': dict(spec='dlls/win32u/win32u.spec', headers=['include/ntgdi.h', 'include/ntuser.h'], out='dlls/win32u'),
}

def split_params(p):
    out, depth, cur = [], 0, ''
    for ch in p:
        if ch in '([': depth += 1
        if ch in ')]': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

KEYWORDS = {'unsigned', 'signed', 'long', 'short', 'int', 'char', 'const', 'struct', 'enum', 'union', 'void', 'volatile'}

def strip_name(param):
    """'const void *bits' -> 'const void *' ; 'ULONG' -> 'ULONG' ; 'HANDLE xform' -> 'HANDLE'"""
    param = re.sub(r'\s+', ' ', param.strip())
    m = re.match(r'^(.*?[\*\s])([A-Za-z_]\w*)$', param)
    if m:
        head, name = m.group(1).strip(), m.group(2)
        if head and name not in KEYWORDS and not (head.split()[-1] in ('struct', 'enum', 'union')):
            # unnamed typedef pairs like 'unsigned long' keep their last word because it is a keyword
            return head
    return param

for mod, cfg in mods.items():
    protos, rets = {}, {}
    for h in cfg['headers']:
        txt = open(os.path.join(src, h)).read()
        for m in re.finditer(r'([A-Za-z_][\w \t\*]*?)\b(Nt\w+)\s*\(([^;{}]*?)\)\s*;', txt):
            protos.setdefault(m.group(2), split_params(m.group(3)))
            r = re.sub(r'\b(NTSYSAPI|W32KAPI|WINAPI|extern)\b', '', m.group(1)).strip()
            rets.setdefault(m.group(2), r)
    names = []
    for line in open(os.path.join(src, cfg['spec'])):
        if '-syscall' not in line: continue
        m = re.match(r'@\s+(?:stdcall|cdecl)\s+(?:-\w+(?:=\S+)?\s+)*?(\w+)\(([^)]*)\)', line)
        if m and len(m.group(2).split()) > 8: names.append(m.group(1))
    thunks, rename, unrename, skipped = [], [], [], []
    for n in names:
        if n not in protos:
            skipped.append(n); continue
        ps = [strip_name(p) for p in protos[n]]
        if ps == ['void'] or len(ps) <= 8: skipped.append(n); continue
        params = ', '.join('ULONG_PTR a%d' % i for i in range(len(ps)))
        args = ', '.join('(%s)a%d' % (t, i) for i, t in enumerate(ps))
        ret = rets[n]
        thunks.append('static %s WINAPI apple_stack_%s( %s )\n{\n    return %s( %s );\n}\n' % (ret, n, params, n, args))
        rename.append('#define %s apple_stack_%s' % (n, n))
        unrename.append('#undef %s' % n)
    base = os.path.join(src, cfg['out'])
    hdr = ('/* Generated by scripts/gen-apple-stack-thunks.py - do not edit.\n'
           ' * Darwin-ABI adapters for syscalls with more than 8 arguments (see the script for the reason). */\n')
    open(os.path.join(base, 'apple_stack_thunks.h'), 'w').write(hdr + '\n' + '\n'.join(thunks))
    open(os.path.join(base, 'apple_stack_thunks_rename.h'), 'w').write(hdr + '\n'.join(rename) + '\n')
    open(os.path.join(base, 'apple_stack_thunks_unrename.h'), 'w').write(hdr + '\n'.join(unrename) + '\n')
    print(mod, 'thunks:', len(thunks), 'skipped:', skipped)
